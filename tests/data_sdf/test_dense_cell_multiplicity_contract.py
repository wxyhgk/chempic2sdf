import pytest

from tools.audit_dense_cell_multiplicity_contract import MANIFEST, audit


def test_collision_evidence_has_train_positives_but_fails_closed_without_candidate_contract():
    result = audit()
    assert result["record_counts"]["collision_train"] >= 50
    assert result["record_counts"]["collision_holdout"] > 0
    assert result["checks"]["train_collision_positives_ge_50"] is True
    assert result["checks"]["multi_slot_candidate_schema"] is False
    assert result["checks"]["hard_negative_precision_available"] is False
    assert result["checks"]["protected_old_selected_retention_100"] is False
    assert result["gate"]["cpu_contract_pass"] is False
    assert result["gate"]["gpu_training_authorized"] is False


def test_diagnostic_is_read_only_and_does_not_claim_selector_rescue():
    result = audit()
    assert result["read_only"] is True
    assert result["training_performed"] is False
    assert result["gpu_used"] is False
    assert result["interpretation"]["not_selector_rescue"] is True


def test_cpu_manifest_passes_without_authorizing_gpu():
    if not MANIFEST.exists():
        pytest.skip("CPU candidate manifest is generated by the read-only replay job")
    result = audit(manifest=MANIFEST)
    assert result["record_counts"]["candidate_records"] > 100_000
    assert result["checks"]["multi_slot_candidate_schema"] is True
    assert result["checks"]["collision_group_schema"] is True
    assert result["checks"]["hard_negative_precision_ge_085"] is True
    assert result["checks"]["protected_old_selected_retention_100"] is True
    assert result["gate"]["cpu_contract_pass"] is True
    assert result["gate"]["gpu_training_authorized"] is False
