"""Decode typed proposal affinities as an exact physical-group partition.

The decoder never creates an anonymous group slot or regresses geometry.  It
unions deployable geometry candidates with candidates generated by several
thresholds of the learned pair affinities, scores each complete candidate,
and asks the shared exact-cover solver to own every usable frozen proposal
exactly once.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
import math
from numbers import Integral, Real
from typing import Any

import numpy as np
import torch

from chemvector.audit_typed_candidate_exact_cover import (
    CandidateGeometryThresholds,
    TypedCandidateGroup,
    generate_typed_candidate_groups,
    generate_typed_candidate_groups_from_affinities,
)
from chemvector.bond_group_exact_cover import (
    BondGroupCandidate,
    BondGroupExactCoverResult,
    BondGroupExactCoverValidationError,
    solve_bond_group_exact_cover,
)
from chemvector.bond_group_proposal_membership import (
    HASHED_WEDGE,
    PARALLEL_2,
    PARALLEL_3,
    PHYSICAL_GROUP_NAMES,
)
from chemvector.bond_group_typed_affinity import (
    PAIR_CLASS_FOR_GROUP_TYPE,
    PAIR_CLASS_NAMES,
)
from chemvector.primitive_set import LINE, QUAD, TRIANGLE


_PHYSICAL_PROPOSAL_TYPES = frozenset((LINE, TRIANGLE, QUAD))
_PAIR_GROUP_TYPES = (PARALLEL_2, PARALLEL_3, HASHED_WEDGE)


class TypedAffinityPackingValidationError(ValueError):
    """Raised when decoder inputs violate the frozen-proposal protocol."""


@dataclass(frozen=True, slots=True)
class TypedAffinityPackingConfig:
    """Fixed candidate and exact-cover settings for v0.9.7 decoding."""

    # Capacity100 calibration: lower sweeps create thousands of overlapping
    # hashed candidates and obscure the exact-cover objective.
    learned_affinity_thresholds: tuple[float, ...] = (0.90, 0.95)
    geometry_thresholds: CandidateGeometryThresholds = field(
        default_factory=CandidateGeometryThresholds
    )
    exact_cover_time_limit_seconds: float | None = 5.0
    pair_symmetry_tolerance: float = 1e-6

    def __post_init__(self) -> None:
        raw_thresholds = tuple(self.learned_affinity_thresholds)
        if len(raw_thresholds) < 2:
            raise ValueError("Typed Affinity packing requires multiple thresholds")
        thresholds = tuple(sorted(set(float(value) for value in raw_thresholds)))
        if len(thresholds) != len(raw_thresholds):
            raise ValueError("Learned affinity thresholds must be unique")
        if not all(math.isfinite(value) and 0.0 < value < 1.0 for value in thresholds):
            raise ValueError("Learned affinity thresholds must lie strictly in (0, 1)")
        object.__setattr__(self, "learned_affinity_thresholds", thresholds)

        if self.exact_cover_time_limit_seconds is not None:
            value = self.exact_cover_time_limit_seconds
            if isinstance(value, bool) or not isinstance(value, Real):
                raise ValueError("Exact-cover time limit must be numeric or None")
            value = float(value)
            if not math.isfinite(value) or value <= 0.0:
                raise ValueError("Exact-cover time limit must be finite and positive")
            object.__setattr__(self, "exact_cover_time_limit_seconds", value)

        tolerance = float(self.pair_symmetry_tolerance)
        if not math.isfinite(tolerance) or tolerance < 0.0:
            raise ValueError("Pair symmetry tolerance must be finite and nonnegative")
        object.__setattr__(self, "pair_symmetry_tolerance", tolerance)


@dataclass(frozen=True, slots=True)
class TypedAffinityCandidatePool:
    """Canonical candidate union and audit counts before learned scoring."""

    candidates: tuple[TypedCandidateGroup, ...]
    candidate_counts: Mapping[str, int]
    candidate_sources: Mapping[TypedCandidateGroup, tuple[str, ...]]


@dataclass(frozen=True, slots=True)
class TypedAffinityPackingResult:
    """Typed rows plus the exact-cover diagnostics required by evaluators."""

    typed_rows: tuple[dict[str, Any], ...]
    candidate_counts: Mapping[str, int]
    feasible: bool
    objective: float | None
    solver_latency_ms: float
    solver_status: str
    solver_status_code: int
    solver_message: str

    @property
    def rows(self) -> tuple[dict[str, Any], ...]:
        return self.typed_rows

    @property
    def latency_ms(self) -> float:
        return self.solver_latency_ms


@dataclass(frozen=True, slots=True)
class _ValidatedSample:
    node_logits: np.ndarray
    pair_logits: np.ndarray
    proposal_geometry: np.ndarray
    proposal_types: np.ndarray
    usable_mask: np.ndarray


def _as_numpy(value: torch.Tensor | np.ndarray | Sequence[Any]) -> np.ndarray:
    if isinstance(value, torch.Tensor):
        tensor = value.detach().cpu()
        if tensor.dtype == torch.bfloat16:
            tensor = tensor.float()
        return tensor.numpy()
    return np.asarray(value)


def _integer_vector(value: Any, *, name: str) -> np.ndarray:
    array = _as_numpy(value)
    if array.ndim != 1:
        raise TypedAffinityPackingValidationError(f"{name} must be one-dimensional")
    if not np.issubdtype(array.dtype, np.integer):
        try:
            numeric = array.astype(np.float64)
        except (TypeError, ValueError) as error:
            raise TypedAffinityPackingValidationError(
                f"{name} must contain integers"
            ) from error
        if not np.isfinite(numeric).all() or not np.equal(numeric, np.rint(numeric)).all():
            raise TypedAffinityPackingValidationError(
                f"{name} must contain integers"
            )
    return array.astype(np.int64, copy=False)


def _boolean_vector(value: Any, *, name: str) -> np.ndarray:
    array = _as_numpy(value)
    if array.ndim != 1:
        raise TypedAffinityPackingValidationError(f"{name} must be one-dimensional")
    if array.dtype != np.bool_:
        try:
            numeric = array.astype(np.float64)
        except (TypeError, ValueError) as error:
            raise TypedAffinityPackingValidationError(
                f"{name} must contain booleans or zero/one values"
            ) from error
        if not np.isfinite(numeric).all() or not np.isin(numeric, (0.0, 1.0)).all():
            raise TypedAffinityPackingValidationError(
                f"{name} must contain booleans or zero/one values"
            )
    return array.astype(bool, copy=False)


def _strict_known_group_count(value: Any) -> int:
    if isinstance(value, torch.Tensor):
        if value.numel() != 1:
            raise TypedAffinityPackingValidationError(
                "known_group_count must be a scalar integer"
            )
        value = value.detach().cpu().item()
    if isinstance(value, np.ndarray):
        if value.size != 1:
            raise TypedAffinityPackingValidationError(
                "known_group_count must be a scalar integer"
            )
        value = value.item()
    if isinstance(value, bool) or not isinstance(value, Integral):
        raise TypedAffinityPackingValidationError(
            "known_group_count must be a scalar integer"
        )
    count = int(value)
    if count < 0:
        raise TypedAffinityPackingValidationError(
            "known_group_count must be nonnegative"
        )
    return count


def _validate_sample(
    output: Mapping[str, Any],
    proposal_geometry: Any,
    proposal_types: Any,
    usable_mask: Any,
    *,
    pair_symmetry_tolerance: float,
) -> _ValidatedSample:
    if not isinstance(output, Mapping):
        raise TypedAffinityPackingValidationError("Model output must be a mapping")
    missing = {
        "node_group_type_logits",
        "pair_logits",
    } - output.keys()
    if missing:
        raise TypedAffinityPackingValidationError(
            f"Typed Affinity output fields are missing: {sorted(missing)}"
        )

    geometry = _as_numpy(proposal_geometry).astype(np.float64, copy=False)
    if geometry.ndim != 2 or geometry.shape[1] != 8:
        raise TypedAffinityPackingValidationError(
            "Proposal geometry must have shape [proposals, 8]"
        )
    proposals = geometry.shape[0]
    types = _integer_vector(proposal_types, name="proposal_types")
    usable = _boolean_vector(usable_mask, name="usable_mask")
    if types.shape != (proposals,) or usable.shape != (proposals,):
        raise TypedAffinityPackingValidationError(
            "Proposal types/mask must align with proposal geometry"
        )

    node_logits = _as_numpy(output["node_group_type_logits"]).astype(
        np.float64,
        copy=False,
    )
    pair_logits = _as_numpy(output["pair_logits"]).astype(np.float64, copy=False)
    expected_node = (proposals, len(PHYSICAL_GROUP_NAMES))
    expected_pair = (proposals, proposals, len(PAIR_CLASS_NAMES))
    if node_logits.shape != expected_node:
        raise TypedAffinityPackingValidationError(
            f"node_group_type_logits must have shape {expected_node}"
        )
    if pair_logits.shape != expected_pair:
        raise TypedAffinityPackingValidationError(
            f"pair_logits must have shape {expected_pair}"
        )
    if not np.isfinite(node_logits).all() or not np.isfinite(pair_logits).all():
        raise TypedAffinityPackingValidationError("Typed Affinity logits must be finite")
    if not np.allclose(
        pair_logits,
        pair_logits.transpose(1, 0, 2),
        rtol=0.0,
        atol=pair_symmetry_tolerance,
    ):
        raise TypedAffinityPackingValidationError(
            "Typed Affinity pair logits must be symmetric"
        )
    pair_logits = 0.5 * (pair_logits + pair_logits.transpose(1, 0, 2))

    if not np.isfinite(geometry[usable]).all():
        raise TypedAffinityPackingValidationError(
            "Usable proposal geometry must be finite"
        )
    active_types = types[usable]
    unsupported = sorted(set(active_types.tolist()) - _PHYSICAL_PROPOSAL_TYPES)
    if unsupported:
        raise TypedAffinityPackingValidationError(
            f"Usable proposals contain unsupported physical types: {unsupported}"
        )
    for proposal_index in np.flatnonzero(usable & (types == LINE)):
        points = geometry[proposal_index, :4].reshape(2, 2)
        if float(np.linalg.norm(points[1] - points[0])) <= 1e-9:
            raise TypedAffinityPackingValidationError(
                f"Usable line proposal {int(proposal_index)} is degenerate"
            )

    return _ValidatedSample(
        node_logits=node_logits,
        pair_logits=pair_logits,
        proposal_geometry=geometry,
        proposal_types=types,
        usable_mask=usable,
    )


def _log_softmax(values: np.ndarray, *, axis: int = -1) -> np.ndarray:
    maximum = np.max(values, axis=axis, keepdims=True)
    shifted = values - maximum
    return shifted - np.log(np.exp(shifted).sum(axis=axis, keepdims=True))


def _learned_pair_affinities(
    pair_probabilities: np.ndarray,
    proposal_types: np.ndarray,
    usable_mask: np.ndarray,
    threshold: float,
) -> dict[int, np.ndarray]:
    line_mask = usable_mask & (proposal_types == LINE)
    valid_pairs = line_mask[:, None] & line_mask[None, :]
    np.fill_diagonal(valid_pairs, False)
    result: dict[int, np.ndarray] = {}
    for group_type in _PAIR_GROUP_TYPES:
        pair_class = PAIR_CLASS_FOR_GROUP_TYPE[group_type]
        affinity = (pair_probabilities[..., pair_class] >= threshold) & valid_pairs
        affinity = affinity | affinity.T
        np.fill_diagonal(affinity, False)
        result[group_type] = affinity
    return result


def _candidate_count_map(
    geometry_candidates: set[TypedCandidateGroup],
    learned_candidates: set[TypedCandidateGroup],
    union: set[TypedCandidateGroup],
    threshold_counts: Mapping[float, int],
) -> dict[str, int]:
    counts = {
        "geometry": len(geometry_candidates),
        "learned": len(learned_candidates),
        "learned_only": len(learned_candidates - geometry_candidates),
        "union": len(union),
        "total": len(union),
    }
    for threshold, count in sorted(threshold_counts.items()):
        counts[f"learned@{threshold:.3f}"] = count
    for group_type, kind in enumerate(PHYSICAL_GROUP_NAMES):
        if group_type == 0:
            continue
        counts[f"union:{kind}"] = sum(
            candidate.group_type == group_type for candidate in union
        )
    return counts


def _build_candidate_pool_from_validated(
    sample: _ValidatedSample,
    config: TypedAffinityPackingConfig,
) -> TypedAffinityCandidatePool:
    geometry_candidates = set(
        generate_typed_candidate_groups(
            sample.proposal_geometry,
            sample.proposal_types,
            sample.usable_mask,
            thresholds=config.geometry_thresholds,
        )
    )
    pair_probabilities = np.exp(_log_softmax(sample.pair_logits))
    sources: dict[TypedCandidateGroup, set[str]] = {
        candidate: {"geometry"} for candidate in geometry_candidates
    }
    learned_candidates: set[TypedCandidateGroup] = set()
    threshold_counts: dict[float, int] = {}
    for threshold in config.learned_affinity_thresholds:
        affinities = _learned_pair_affinities(
            pair_probabilities,
            sample.proposal_types,
            sample.usable_mask,
            threshold,
        )
        generated = set(
            generate_typed_candidate_groups_from_affinities(
                sample.proposal_geometry,
                sample.proposal_types,
                sample.usable_mask,
                affinities,
                thresholds=config.geometry_thresholds,
            )
        )
        threshold_counts[threshold] = len(generated)
        learned_candidates.update(generated)
        source_name = f"learned@{threshold:.3f}"
        for candidate in generated:
            sources.setdefault(candidate, set()).add(source_name)

    union = geometry_candidates | learned_candidates
    candidates = tuple(sorted(union))
    return TypedAffinityCandidatePool(
        candidates=candidates,
        candidate_counts=_candidate_count_map(
            geometry_candidates,
            learned_candidates,
            union,
            threshold_counts,
        ),
        candidate_sources={
            candidate: tuple(sorted(sources[candidate])) for candidate in candidates
        },
    )


def build_typed_affinity_candidate_pool(
    output: Mapping[str, Any],
    proposal_geometry: Any,
    proposal_types: Any,
    usable_mask: Any,
    *,
    config: TypedAffinityPackingConfig = TypedAffinityPackingConfig(),
) -> TypedAffinityCandidatePool:
    """Build the geometry/learned candidate union without GT memberships."""

    sample = _validate_sample(
        output,
        proposal_geometry,
        proposal_types,
        usable_mask,
        pair_symmetry_tolerance=config.pair_symmetry_tolerance,
    )
    return _build_candidate_pool_from_validated(sample, config)


def _typed_candidate_log_score(
    candidate: TypedCandidateGroup,
    node_log_probabilities: np.ndarray,
    pair_log_probabilities: np.ndarray,
) -> float:
    members = np.asarray(candidate.members, dtype=np.int64)
    node_score = float(
        node_log_probabilities[members, candidate.group_type].mean()
    )
    pair_class = PAIR_CLASS_FOR_GROUP_TYPE.get(candidate.group_type)
    if pair_class is None:
        return node_score
    offsets = np.triu_indices(len(members), k=1)
    pair_score = float(
        pair_log_probabilities[
            members[offsets[0]],
            members[offsets[1]],
            pair_class,
        ].mean()
    )
    return node_score + pair_score


def _solve_validated_candidates(
    candidates: Iterable[TypedCandidateGroup],
    sample: _ValidatedSample,
    known_group_count: int,
    *,
    time_limit_seconds: float | None,
    candidate_sources: Mapping[TypedCandidateGroup, tuple[str, ...]] | None = None,
) -> BondGroupExactCoverResult:
    try:
        unique = tuple(sorted(set(candidates)))
    except TypeError as error:
        raise TypedAffinityPackingValidationError(
            "Candidate pool must contain TypedCandidateGroup values"
        ) from error
    if any(not isinstance(candidate, TypedCandidateGroup) for candidate in unique):
        raise TypedAffinityPackingValidationError(
            "Candidate pool must contain TypedCandidateGroup values"
        )

    node_log_probabilities = _log_softmax(sample.node_logits)
    pair_log_probabilities = _log_softmax(sample.pair_logits)
    scored = []
    for candidate in unique:
        metadata = None
        if candidate_sources is not None:
            metadata = {"sources": tuple(candidate_sources.get(candidate, ()))}
        scored.append(
            BondGroupCandidate(
                group_type=candidate.group_type,
                proposal_indices=candidate.members,
                score=_typed_candidate_log_score(
                    candidate,
                    node_log_probabilities,
                    pair_log_probabilities,
                ),
                metadata=metadata,
            )
        )

    active = tuple(int(value) for value in np.flatnonzero(sample.usable_mask))
    type_by_index = {
        proposal_index: int(sample.proposal_types[proposal_index])
        for proposal_index in active
    }
    try:
        return solve_bond_group_exact_cover(
            tuple(scored),
            type_by_index,
            active_proposal_indices=active,
            known_group_count=known_group_count,
            time_limit_seconds=time_limit_seconds,
        )
    except BondGroupExactCoverValidationError as error:
        raise TypedAffinityPackingValidationError(str(error)) from error


def solve_typed_affinity_candidates(
    candidates: Iterable[TypedCandidateGroup],
    output: Mapping[str, Any],
    proposal_types: Any,
    usable_mask: Any,
    known_group_count: Any,
    *,
    time_limit_seconds: float | None = 5.0,
    pair_symmetry_tolerance: float = 1e-6,
) -> BondGroupExactCoverResult:
    """Score and solve an explicit candidate pool, independent of its order."""

    types = _integer_vector(proposal_types, name="proposal_types")
    usable = _boolean_vector(usable_mask, name="usable_mask")
    if types.shape != usable.shape:
        raise TypedAffinityPackingValidationError(
            "Proposal types and usable mask must align"
        )
    dummy_geometry = np.zeros((len(types), 8), dtype=np.float64)
    for index in np.flatnonzero(usable & (types == LINE)):
        dummy_geometry[index, 2] = 1.0
    sample = _validate_sample(
        output,
        dummy_geometry,
        types,
        usable,
        pair_symmetry_tolerance=float(pair_symmetry_tolerance),
    )
    count = _strict_known_group_count(known_group_count)
    return _solve_validated_candidates(
        candidates,
        sample,
        count,
        time_limit_seconds=time_limit_seconds,
    )


def _typed_rows(result: BondGroupExactCoverResult) -> tuple[dict[str, Any], ...]:
    if not result.feasible:
        return ()
    selected = sorted(
        result.selected_candidates,
        key=lambda candidate: (
            candidate.proposal_indices[0],
            int(candidate.group_type),
            candidate.proposal_indices,
        ),
    )
    return tuple(
        {
            "score": float(candidate.score),
            "type": int(candidate.group_type),
            "kind": str(candidate.kind),
            "member_count": len(candidate.proposal_indices),
            "support_count": len(candidate.proposal_indices),
            "proposal_indices": list(candidate.proposal_indices),
            "valid_membership": True,
        }
        for candidate in selected
    )


def decode_typed_affinity_packing(
    output: Mapping[str, Any],
    proposal_geometry: Any,
    proposal_types: Any,
    usable_mask: Any,
    known_group_count: Any,
    *,
    config: TypedAffinityPackingConfig = TypedAffinityPackingConfig(),
) -> TypedAffinityPackingResult:
    """Decode one sample into a typed, once-covered frozen-proposal partition."""

    sample = _validate_sample(
        output,
        proposal_geometry,
        proposal_types,
        usable_mask,
        pair_symmetry_tolerance=config.pair_symmetry_tolerance,
    )
    count = _strict_known_group_count(known_group_count)
    pool = _build_candidate_pool_from_validated(sample, config)
    exact_cover = _solve_validated_candidates(
        pool.candidates,
        sample,
        count,
        time_limit_seconds=config.exact_cover_time_limit_seconds,
        candidate_sources=pool.candidate_sources,
    )
    return TypedAffinityPackingResult(
        typed_rows=_typed_rows(exact_cover),
        candidate_counts=pool.candidate_counts,
        feasible=exact_cover.feasible,
        objective=exact_cover.objective,
        solver_latency_ms=exact_cover.latency_ms,
        solver_status=exact_cover.solver_status,
        solver_status_code=exact_cover.solver_status_code,
        solver_message=exact_cover.solver_message,
    )


